#!/usr/bin/env bash
# Rebuild js/gallery-data.js from whatever is in img/gallery/.
#
#     ./tools/build-gallery.sh
#
# Layout — one folder per category, folder name becomes the filter chip:
#
#   img/gallery/
#     apparel/     name.jpg              full size, used by the lightbox
#       thumbs/    name-400.jpg ...      responsive variants (build-thumbs.sh)
#     gym/  studio/  automotive/  ...    add any folder; it becomes a chip
#     remote.txt                         images hosted elsewhere
#     cdn.txt                            optional CDN base URL (see below)
#
# Adding photos is: drop files in a folder, run build-thumbs.sh, run this,
# commit. No HTML and no JavaScript to edit — chips, counts, captions, srcset
# and masonry row spans all come from the manifest.
#
# SERVING FROM A CDN
# Put a single line in img/gallery/cdn.txt, e.g.
#     https://cdn.jsdelivr.net/gh/yherhr/mkm-media@main/
# and every generated path is prefixed with it. The CDN repo must mirror the
# img/gallery/... structure. Delete or blank the file to go back to local
# paths. It is read at build time, so the setting survives a rebuild.
#
# ImageMagick is used to read real pixel widths for the srcset descriptors.
# Without it the manifest still builds; it just falls back to a single src.

set -euo pipefail
cd "$(dirname "$0")/.."

ROOT="img/gallery"
OUT="js/gallery-data.js"
WIDTHS=(400 700 1000 1400)

[[ -d "$ROOT" ]] || {
  echo "No $ROOT folder yet. Create one subfolder per category, e.g.:"
  for c in studio gym outdoor family product apparel; do echo "  mkdir -p $ROOT/$c"; done
  exit 1
}

HAVE_IDENTIFY=0
command -v identify >/dev/null 2>&1 && HAVE_IDENTIFY=1
[[ $HAVE_IDENTIFY -eq 0 ]] && echo "note: ImageMagick not found — no srcset, dimensions measured in the browser"

PREFIX=""
if [[ -f "$ROOT/cdn.txt" ]]; then
  PREFIX=$(grep -v '^[[:space:]]*#' "$ROOT/cdn.txt" | grep -v '^[[:space:]]*$' | head -1 | tr -d '[:space:]' || true)
  if [[ -n "$PREFIX" ]]; then
    [[ "${PREFIX: -1}" != "/" ]] && PREFIX="${PREFIX}/"
    echo "  serving from: $PREFIX"
  fi
fi

label_for() {
  case "$1" in
    studio)     echo "Studio Modelling" ;;
    gym)        echo "Gym Modelling" ;;
    outdoor)    echo "Outdoor Modelling" ;;
    family)     echo "Family Moments" ;;
    product)    echo "Product Photography" ;;
    business)   echo "Business Photography" ;;
    apparel)    echo "Apparel & Brand" ;;
    sport)      echo "Combat Sport" ;;
    automotive) echo "Automotive" ;;
    *)          echo "$(tr '[:lower:]' '[:upper:]' <<< "${1:0:1}")${1:1}" ;;
  esac
}

{
  echo "/* =========================================================================="
  echo "   GALLERY MANIFEST — generated by tools/build-gallery.sh on $(date +%F)."
  echo "   Do not edit by hand; add files to img/gallery/<category>/ and re-run it."
  echo "   ========================================================================== */"
  echo "window.MKM_PHOTOS = ["
} > "$OUT"

total=0
first=1

for dir in "$ROOT"/*/; do
  [[ -d "$dir" ]] || continue
  cat_slug=$(basename "$dir")
  [[ "$cat_slug" == "thumbs" ]] && continue
  cat_label=$(label_for "$cat_slug")
  n=0

  while IFS= read -r f; do
    [[ -e "$f" ]] || continue
    tdir="$(dirname "$f")/thumbs"
    bn="$(basename "${f%.*}")"

    dims=""; ow=""
    if [[ $HAVE_IDENTIFY -eq 1 ]]; then
      wh=$(identify -format '%w %h' "$f[0]" 2>/dev/null || true)
      if [[ -n "$wh" ]]; then
        ow="${wh%% *}"
        dims=", w: ${wh%% *}, h: ${wh##* }"
      fi
    fi

    srcset=""; default="$f"; seen=" "
    for w in "${WIDTHS[@]}"; do
      tf="$tdir/${bn}-${w}.jpg"
      [[ -f "$tf" ]] || continue
      tw=$w
      if [[ $HAVE_IDENTIFY -eq 1 ]]; then
        tw=$(identify -format '%w' "$tf[0]" 2>/dev/null || echo "$w")
      fi
      # a repeated w descriptor is invalid — skip anything already covered
      [[ "$seen" == *" $tw "* ]] && continue
      [[ -n "$ow" && "$tw" -ge "$ow" ]] && continue
      seen="${seen}${tw} "
      [[ -n "$srcset" ]] && srcset="${srcset}, "
      srcset="${srcset}${PREFIX}${tf} ${tw}w"
      [[ "$w" == "700" ]] && default="$tf"
    done
    if [[ -n "$srcset" && -n "$ow" ]]; then
      srcset="${srcset}, ${PREFIX}${f} ${ow}w"
    fi

    entry="  { src: \"${PREFIX}${default}\", cat: \"${cat_slug}\", label: \"${cat_label}\""
    [[ "$default" != "$f" ]] && entry="${entry}, full: \"${PREFIX}${f}\""
    [[ -n "$srcset" ]] && entry="${entry}, srcset: \"${srcset}\""
    entry="${entry}${dims} }"

    [[ $first -eq 0 ]] && echo "," >> "$OUT"
    printf '%s' "$entry" >> "$OUT"
    first=0
    n=$((n + 1)); total=$((total + 1))
  done < <(find "$dir" -maxdepth 1 -type f \
             \( -iname '*.jpg' -o -iname '*.jpeg' -o -iname '*.png' -o -iname '*.webp' -o -iname '*.avif' \) \
           | sort)

  printf "  %-12s %d\n" "$cat_slug" "$n"
done

REMOTE="$ROOT/remote.txt"
if [[ -f "$REMOTE" ]]; then
  rn=0
  while IFS='|' read -r url cat label; do
    url="${url#"${url%%[![:space:]]*}"}"; url="${url%"${url##*[![:space:]]}"}"
    [[ -z "$url" || "$url" == \#* ]] && continue
    cat="${cat#"${cat%%[![:space:]]*}"}";   cat="${cat%"${cat##*[![:space:]]}"}"
    label="${label#"${label%%[![:space:]]*}"}"; label="${label%"${label##*[![:space:]]}"}"
    [[ -z "$label" ]] && label=$(label_for "$cat")
    [[ $first -eq 0 ]] && echo "," >> "$OUT"
    printf '  { src: "%s", cat: "%s", label: "%s" }' "$url" "$cat" "$label" >> "$OUT"
    first=0
    rn=$((rn + 1)); total=$((total + 1))
  done < "$REMOTE"
  printf "  %-12s %d  (remote.txt)\n" "hosted" "$rn"
fi

{ echo ""; echo "];"; } >> "$OUT"

dupes=$(find "$ROOT" -mindepth 2 -maxdepth 2 -type f \
          \( -iname '*.jpg' -o -iname '*.jpeg' -o -iname '*.png' -o -iname '*.webp' -o -iname '*.avif' \) \
        -printf '%f\n' 2>/dev/null | sort | uniq -d)
if [[ -n "$dupes" ]]; then
  echo
  echo "WARNING — the same filename appears in more than one category folder:"
  while IFS= read -r f; do
    [[ -z "$f" ]] && continue
    printf '  %s\n' "$f"
    find "$ROOT" -mindepth 2 -maxdepth 2 -type f -name "$f" -printf '      %h\n'
  done <<< "$dupes"
  echo "  Each will show twice. Delete the copy you don't want, then run this again."
fi

echo
echo "Wrote $OUT — $total images."
command -v node >/dev/null 2>&1 && node --check "$OUT" && echo "Syntax OK"
echo
echo "Remember: ./tools/stamp-assets.sh after this, or browsers keep the old manifest."
