#!/usr/bin/env bash
# Assemble a push-ready media repo from img/gallery/.
#
#     ./tools/make-media-repo.sh ../mkm-media
#
# Copies img/gallery/ (originals + variants) into the target folder, preserving
# the img/gallery/... structure that the CDN URLs expect, and git-inits it.
# Then:
#
#     cd ../mkm-media
#     git remote add origin https://github.com/yherhr/mkm-media.git
#     git push -u origin main
#     cd -  &&  ./tools/use-cdn.sh https://cdn.jsdelivr.net/gh/yherhr/mkm-media@main
#
# The media repo must be PUBLIC — jsDelivr can't read private repos.
#
# IS THIS WORTH DOING? Serving from GitHub Pages is already CDN-backed, so this
# is mostly about keeping the site repo small, not about speed. Weigh it against
# jsDelivr's 50 MB per-repo cap, which the report below measures against.

set -euo pipefail
cd "$(dirname "$0")/.."

DEST="${1:?usage: make-media-repo.sh <target-folder>}"

mkdir -p "$DEST/img"
cp -a img/gallery "$DEST/img/"
rm -f "$DEST/img/gallery/cdn.txt" "$DEST/img/gallery/remote.txt" "$DEST/img/gallery/.gitkeep"

cat > "$DEST/README.md" <<'EOF'
# Max K Media — gallery media

Image files for the Max K Media site, served through jsDelivr.

    https://cdn.jsdelivr.net/gh/<owner>/<repo>@main/img/gallery/<category>/<file>

Generated by tools/make-media-repo.sh in the site repo. Don't edit here —
add photos to the site repo's img/gallery/, regenerate, and re-run that script.

Must stay public: jsDelivr cannot read private repositories.
EOF

if [[ ! -d "$DEST/.git" ]]; then
  git -C "$DEST" init -q -b main
  git -C "$DEST" add -A
  git -C "$DEST" -c user.email=media@local -c user.name=media commit -qm "Gallery media" || true
fi

bytes=$(du -sk "$DEST/img" | cut -f1)
mb=$((bytes / 1024))
files=$(find "$DEST/img" -type f | wc -l)
biggest=$(find "$DEST/img" -type f -printf '%s %p\n' | sort -rn | head -1)

echo
printf "  %s files, %d MB\n" "$files" "$mb"
printf "  largest: %s KB  %s\n" "$(( ${biggest%% *} / 1024 ))" "${biggest#* }"
echo
echo "  jsDelivr /gh/ limits: 20 MB per file, 50 MB per repo"
if [[ $mb -ge 50 ]]; then
  echo "  OVER the 50 MB repo cap — jsDelivr will refuse. Use Cloudflare R2 or Bunny.net instead."
elif [[ $mb -ge 35 ]]; then
  echo "  Within the cap but close. One more batch of photos will likely exceed it."
else
  echo "  Comfortably inside the cap — $(( 50 - mb )) MB of headroom."
fi
echo
echo "Next: push $DEST, then ./tools/use-cdn.sh <base-url>"
