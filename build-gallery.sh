#!/usr/bin/env bash
# Rebuild js/gallery-data.js from whatever is in img/gallery/.
#
#   ./tools/build-gallery.sh
#
# Layout — one folder per category, folder name becomes the filter chip:
#
#   img/gallery/
#     studio/      _DSC5307.jpg  _DSC5448.jpg  ...
#     gym/
#     outdoor/
#     family/
#     product/
#     business/    (add any folder you like; it becomes a chip automatically)
#
# Adding photos is then: drop files in a folder, run this, commit. No HTML and
# no JavaScript to edit — chips, counts and captions all come from the manifest.
#
# If ImageMagick is installed the script records each image's real dimensions,
# which lets the masonry lay out correctly on first paint instead of reflowing
# as images arrive. Without it, everything still works; the layout just settles
# a fraction later.

set -euo pipefail
cd "$(dirname "$0")/.."

ROOT="img/gallery"
OUT="js/gallery-data.js"

if [[ ! -d "$ROOT" ]]; then
  echo "No $ROOT folder yet. Create it with one subfolder per category, e.g.:"
  echo "  mkdir -p $ROOT/{studio,gym,outdoor,family,product,business}"
  exit 1
fi

HAVE_IDENTIFY=0
command -v identify >/dev/null 2>&1 && HAVE_IDENTIFY=1
[[ $HAVE_IDENTIFY -eq 0 ]] && echo "note: ImageMagick not found — dimensions will be measured in the browser instead"

# Turn a folder name into a caption: "studio" -> "Studio", "gym" -> "Gym Modelling"
label_for() {
  case "$1" in
    studio)   echo "Studio Modelling" ;;
    gym)      echo "Gym Modelling" ;;
    outdoor)  echo "Outdoor Modelling" ;;
    family)   echo "Family Moments" ;;
    product)    echo "Product Photography" ;;
    business)   echo "Business Photography" ;;
    apparel)    echo "Apparel & Brand" ;;
    sport)      echo "Combat Sport" ;;
    automotive) echo "Automotive" ;;
    *)        echo "$(tr '[:lower:]' '[:upper:]' <<< "${1:0:1}")${1:1}" ;;
  esac
}

{
  echo "/* =========================================================================="
  echo "   GALLERY MANIFEST — generated by tools/build-gallery.sh on $(date +%F)."
  echo "   Do not edit by hand; add files to img/gallery/<category>/ and re-run it."
  echo "   ========================================================================== */"
  echo "window.MKM_PHOTOS = ["
} > "$OUT"

total=0
first=1

for dir in "$ROOT"/*/; do
  [[ -d "$dir" ]] || continue
  cat_slug=$(basename "$dir")
  cat_label=$(label_for "$cat_slug")
  n=0

  while IFS= read -r f; do
    [[ -e "$f" ]] || continue
    dims=""
    if [[ $HAVE_IDENTIFY -eq 1 ]]; then
      wh=$(identify -format '%w %h' "$f[0]" 2>/dev/null || true)
      if [[ -n "$wh" ]]; then
        dims=", w: ${wh%% *}, h: ${wh##* }"
      fi
    fi
    [[ $first -eq 0 ]] && echo "," >> "$OUT"
    printf '  { src: "%s", cat: "%s", label: "%s"%s }' "$f" "$cat_slug" "$cat_label" "$dims" >> "$OUT"
    first=0
    n=$((n + 1)); total=$((total + 1))
  done < <(find "$dir" -maxdepth 1 -type f \
             \( -iname '*.jpg' -o -iname '*.jpeg' -o -iname '*.png' -o -iname '*.webp' -o -iname '*.avif' \) \
           | sort)

  printf "  %-12s %d\n" "$cat_slug" "$n"
done

# Images hosted elsewhere (CDN, another repo) listed in img/gallery/remote.txt
REMOTE="$ROOT/remote.txt"
if [[ -f "$REMOTE" ]]; then
  rn=0
  while IFS='|' read -r url cat label; do
    url="${url#"${url%%[![:space:]]*}"}"; url="${url%"${url##*[![:space:]]}"}"
    [[ -z "$url" || "$url" == \#* ]] && continue
    cat="${cat#"${cat%%[![:space:]]*}"}";   cat="${cat%"${cat##*[![:space:]]}"}"
    label="${label#"${label%%[![:space:]]*}"}"; label="${label%"${label##*[![:space:]]}"}"
    [[ -z "$label" ]] && label=$(label_for "$cat")
    [[ $first -eq 0 ]] && echo "," >> "$OUT"
    printf '  { src: "%s", cat: "%s", label: "%s" }' "$url" "$cat" "$label" >> "$OUT"
    first=0
    rn=$((rn + 1)); total=$((total + 1))
  done < "$REMOTE"
  printf "  %-12s %d  (remote.txt)\n" "hosted" "$rn"
fi

{
  echo ""
  echo "];"
} >> "$OUT"

# same filename in more than one category = almost certainly an accident
dupes=$(find "$ROOT" -mindepth 2 -type f \
          \( -iname '*.jpg' -o -iname '*.jpeg' -o -iname '*.png' -o -iname '*.webp' -o -iname '*.avif' \) \
        -printf '%f\n' 2>/dev/null | sort | uniq -d)
if [[ -n "$dupes" ]]; then
  echo
  echo "WARNING — the same filename appears in more than one category folder:"
  while IFS= read -r f; do
    [[ -z "$f" ]] && continue
    printf '  %s\n' "$f"
    find "$ROOT" -mindepth 2 -type f -name "$f" -printf '      %h\n'
  done <<< "$dupes"
  echo "  Each of these will show twice in the gallery. Delete the copy you don't want,"
  echo "  then run this again."
fi

echo
echo "Wrote $OUT — $total images."

if command -v node >/dev/null 2>&1; then
  node --check "$OUT" && echo "Syntax OK"
fi

echo
echo "Reminder: GitHub Pages caps a published site at 1 GB and jsDelivr's /gh/"
echo "endpoint caps files at 20 MB and a whole repo at 50 MB. Run"
echo "./tools/optimise-images.sh first if these are camera originals."
